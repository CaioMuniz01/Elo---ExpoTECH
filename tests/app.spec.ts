test('preferências protegidas, cadastro, descoberta, filtros persistidos e logout', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('tab', { name: 'Filtros' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Começar minha história' }).click();
  await page.getByLabel('Seu nome', { exact: true }).fill('Pessoa Teste');
  await page.getByLabel('Idade (18 anos ou mais)', { exact: true }).fill('27');
  await page.getByLabel('E-mail', { exact: true }).fill(`ui-${Date.now()}@exemplo.com`);
  await page.getByLabel('Senha (mínimo 8 caracteres)', { exact: true }).fill('Teste123!');
  await page.getByRole('button', { name: 'Criar minha conta' }).click();
  await expect(page.getByLabel('Descubra seu próximo elo.', { exact: true })).toBeVisible();
  await expect(page.getByLabel('Foto de exemplo de Marina')).toBeVisible();
  await page.waitForFunction(() => Array.from(document.images).some(image => image.alt === 'Foto de exemplo de Marina' && image.complete && image.naturalWidth > 0));
  const portrait = await page.getByLabel('Foto de exemplo de Marina').boundingBox();
  expect(portrait).not.toBeNull();
  expect(portrait!.height).toBeGreaterThan(350);
  expect(await page.getByLabel('Foto de exemplo de Marina').evaluate(element => getComputedStyle(element.firstElementChild!).backgroundSize)).toBe('contain');
  const title = page.getByTestId('app-title');
  const titleBox = await title.boundingBox();
  expect(Math.abs(titleBox!.x + titleBox!.width / 2 - 195)).toBeLessThan(1);
  await expect(title).toHaveCSS('font-family', /Outfit/);
  for (const name of ['Passar', 'Curtir']) {
    const button = await page.getByRole('button', { name, exact: true }).boundingBox();
    expect(button!.y + button!.height).toBeLessThan(844);
  }
  await page.screenshot({ path: 'test-results/descoberta-mobile.png', fullPage: true });
  await page.getByRole('tab', { name: 'Filtros' }).click();
  await page.getByRole('checkbox', { name: 'Católica', exact: true }).click();
  await expect(page.getByRole('radio', { name: /Dar prioridade$/ }).first()).toHaveAttribute('aria-checked', 'true');
  await page.getByRole('radio', { name: /Obrigatório$/ }).first().click();
  await page.getByRole('button', { name: 'Salvar preferências' }).click();
  await expect(page.getByText('Preferências salvas.', { exact: false })).toBeVisible();
  await expect(page.getByRole('tab', { name: 'Descobrir' })).toHaveAttribute('aria-selected', 'true');
  await page.reload(); await page.getByRole('tab', { name: 'Filtros' }).click();
  await expect(page.getByRole('checkbox', { name: 'Católica', exact: true })).toHaveAttribute('aria-checked', 'true');
  await page.getByRole('tab', { name: 'Meu perfil' }).click();
  const logout = page.getByRole('button', { name: 'Sair da conta' });
  await expect(logout).toBeInViewport();
  await logout.click();
  await expect(page.getByRole('button', { name: 'Começar minha história' })).toBeVisible();
  await expect(page.getByRole('tab', { name: 'Filtros' })).toHaveCount(0);
  expect(errors).toEqual([]);
});
