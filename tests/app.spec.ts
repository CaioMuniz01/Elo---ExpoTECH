test('perfis adicionais mostram somente seu retrato e abrem detalhes', async ({ page, request }) => {
  const response = await request.post('http://127.0.0.1:3002/auth/register', { data: { email: `portrait-${Date.now()}@teste.com`, password: 'Teste123!', name: 'Retrato', age: 28 } });
  const { token } = await response.json(); const headers = { Authorization: `Bearer ${token}` };
  const discovery = await (await request.get('http://127.0.0.1:3002/discover', { headers })).json();
  for (const profile of discovery.profiles.filter((p: { id: string }) => !p.id.startsWith('sample-'))) await request.post('http://127.0.0.1:3002/likes', { headers, data: { id: profile.id, kind: 'pass' } });
  await page.addInitScript(value => sessionStorage.setItem('elo.session', value), token);
  await page.goto('/');
  const portrait = page.getByRole('img', { name: 'Foto de exemplo de Lara', exact: true });
  await expect(portrait).toBeVisible();
  await expect(portrait.locator('img')).toBeVisible();
  await expect.poll(() => portrait.locator('img').evaluate(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth > 0)).toBe(true);
  const dimensions = await portrait.locator('img').evaluate(image => { const child = image.getBoundingClientRect(); const frame = image.parentElement!.parentElement!.getBoundingClientRect(); return { x: child.width / frame.width, y: child.height / frame.height }; });
  expect(dimensions.x).toBeCloseTo(2); expect(dimensions.y).toBeCloseTo(2);
  await page.screenshot({ path: 'test-results/perfil-adicional.png' });
  await page.getByRole('button', { name: 'Ver perfil de Lara', exact: true }).click();
  await expect(page.getByRole('img', { name: 'Foto completa de Lara' })).toBeVisible();
});
